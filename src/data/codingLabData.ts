export interface CodingProblem {
  id: string;
  title: string;
  category: 'dsa' | 'dbms' | 'java' | 'python';
  subjectName: string;
  difficulty: 'Easy' | 'Medium' | 'Hard';
  marks: string;
  language: 'c' | 'java' | 'python' | 'sql';
  fileName: string;
  description: string;
  constraints: string[];
  expectedOutput: string;
  starterCode: string;
  modelSolution: string;
  hints: string[];
  validator: (code: string) => { passed: boolean; output: string; error?: string };
}

function makeValidator(tokens: string[], testOutput: string, hint: string) {
  return (code: string) => {
    const missing = tokens.filter(t => !code.toLowerCase().includes(t.toLowerCase()));
    if (missing.length === 0) {
      return {
        passed: true,
        output: testOutput,
      };
    }
    return {
      passed: false,
      output: `[CC] Compilation and test check failed.\nExpected construct missing: "${missing[0]}"\n\nSuggestion: ${hint}`,
      error: `Missing: ${missing[0]}`,
    };
  };
}

